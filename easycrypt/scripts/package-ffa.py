#!/usr/bin/env python3
"""Package the existing FFA definitions and proofs for concrete instantiation."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parent.parent
NAMES = ['FFA', 'FFA_soundness', 'FFA_completeness']

def generate():
    chunks = ['(* GENERATED by scripts/package-ffa.py; edit the original theories. *)\n',
              'abstract theory Model.\n']
    for name in NAMES:
        source = (ROOT / (name + '.ec')).read_text()
        def imports(match):
            names = match.group(1).split()
            external = [n for n in names if n not in NAMES]
            local = [n for n in names if n in NAMES]
            assert all(NAMES.index(n) < NAMES.index(name) for n in local)
            return (('require import ' + ' '.join(external) + '.\n') if external else '') + \
                   (('import ' + ' '.join(local) + '.\n') if local else '')
        source = re.sub(r'require import\s+([\w\s]+)\.', imports, source)
        chunks.append('theory ' + name + '.\n' + source + '\nend ' + name + '.\n')
    chunks.append('end Model.\n')
    return '\n'.join(chunks)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'FFA_Instance.ec'
    text = generate()
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('FFA_Instance.ec is stale: run python3 scripts/package-ffa.py')
    else:
        target.write_text(text)
