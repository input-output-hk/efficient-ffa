#!/usr/bin/env python3
"""Package existing MSM proofs as nested theories so their assumptions can be instantiated.

Adjust imports/root-qualified names and omit the unused FFA LCM declarations.
The generated proofs remain checked by EasyCrypt, and --check detects source drift.
"""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parent.parent
NAMES = [
    'AuxResults', 'MultiScalarMul_Abstract_Setup', 'IterationProps',
    'MultiScalarMul_Abstract', 'MultiScalarMul_Abstract_Soundness',
    'MultiScalarMul_Abstract_Completeness', 'MSM_TableConstruction',
    'MSM_WithTable', 'MSM_RejectionBound', 'MSM_TableConstraints',
    'MSM_WindowOrder', 'MSM_CoordinateWitnesses',
    'MSM_CompleteCoordinates', 'MSM_CoordinateTrace',
    'MSM_CoordinateTables', 'MSM_FullCoordinates',
]

def generate():
    chunks = ['(* GENERATED by scripts/package-msm.py; edit the original theories. *)\n',
              'abstract theory Model.\n']
    for name in NAMES:
        source = (ROOT / (name + '.ec')).read_text()
        if name == 'AuxResults':
            start = source.index('(* Chinese Reminder Theorem')
            end = source.index('lemma mul_weaken6')
            removed = re.sub(r'\(\*.*?\*\)', '', source[start:end], flags=re.S)
            expected = '''op LCM (M : int -> int) (size : int) : int.
                axiom LCM_pos M n : 0 <= LCM M n.
                axiom chinese_reminder_theorem x M size :
                (forall i, 0 <= i < size => x %% M i = 0) <=> x %% LCM M size = 0.'''
            if removed.split() != expected.split():
                raise ValueError('AuxResults LCM block changed; review its exclusion')
            source = source[:start] + source[end:]
        def imports(match):
            names = match.group(1).split()
            external = [n for n in names if n not in NAMES]
            local = [n for n in names if n in NAMES]
            assert all(NAMES.index(n) < NAMES.index(name) for n in local)
            return (('require import ' + ' '.join(external) + '.\n') if external else '') + \
                   (('import ' + ' '.join(local) + '.\n') if local else '')
        source = source.replace('Top.w', 'MultiScalarMul_Abstract.w')
        source = re.sub(r'require import\s+([\w\s]+)\.', imports, source)
        chunks.append('theory ' + name + '.\n' + source + '\nend ' + name + '.\n')
    chunks.append('end Model.\n')
    return '\n'.join(chunks)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'MSM_Instance.ec'
    text = generate()
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('MSM_Instance.ec is stale: run python3 scripts/package-msm.py')
    else:
        target.write_text(text)
